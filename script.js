function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function hasValue(value) {
  return typeof value === "string" && value.trim().length > 0;
}

function withTarget(url) {
  return hasValue(url) ? `href="${escapeHtml(url)}" target="_blank" rel="noreferrer"` : "";
}

function isDirectVideo(url) {
  return hasValue(url) && /\.(mp4|webm|ogg|mov)(\?.*)?$/i.test(url.trim());
}

function normalizeYoutube(url) {
  try {
    const parsed = new URL(url);

    if (parsed.hostname.includes("youtu.be")) {
      return `https://www.youtube.com/embed/${parsed.pathname.slice(1)}`;
    }

    if (parsed.hostname.includes("youtube.com")) {
      const videoId = parsed.searchParams.get("v");
      if (videoId) {
        return `https://www.youtube.com/embed/${videoId}`;
      }

      if (parsed.pathname.startsWith("/embed/")) {
        return url;
      }
    }
  } catch (error) {
    return null;
  }

  return null;
}

function normalizeVimeo(url) {
  try {
    const parsed = new URL(url);
    if (!parsed.hostname.includes("vimeo.com")) {
      return null;
    }

    const id = parsed.pathname.split("/").filter(Boolean).pop();
    return id ? `https://player.vimeo.com/video/${id}` : null;
  } catch (error) {
    return null;
  }
}

function normalizeLoom(url) {
  try {
    const parsed = new URL(url);
    if (!parsed.hostname.includes("loom.com")) {
      return null;
    }

    const parts = parsed.pathname.split("/").filter(Boolean);
    const shareId = parts.at(-1);
    return shareId ? `https://www.loom.com/embed/${shareId}` : null;
  } catch (error) {
    return null;
  }
}

function toEmbedUrl(url) {
  if (!hasValue(url)) {
    return null;
  }

  return normalizeYoutube(url) || normalizeVimeo(url) || normalizeLoom(url);
}

function createEmbed(label, url, description, image) {
  if (isDirectVideo(url)) {
    return `
      <div class="embed-video-card">
        <video
          class="embed-video"
          controls
          playsinline
          preload="metadata"
        >
          <source src="${escapeHtml(url)}" type="video/mp4" />
          Your browser does not support the video tag.
        </video>
      </div>
    `;
  }

  const embedUrl = toEmbedUrl(url);

  if (embedUrl) {
    return `
      <div class="embed-frame">
        <iframe
          src="${escapeHtml(embedUrl)}"
          title="${escapeHtml(label)}"
          loading="lazy"
          allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
          allowfullscreen
        ></iframe>
      </div>
    `;
  }

  if (hasValue(image)) {
    return `
      <div class="embed-image-card">
        <img class="embed-image" src="${escapeHtml(image)}" alt="${escapeHtml(label)}" />
        <div class="embed-image-overlay">
          <span class="placeholder-badge">Featured Sample</span>
          <h3>${escapeHtml(label)}</h3>
          <a class="button button-primary button-small" href="${escapeHtml(url)}" target="_blank" rel="noreferrer">
            Open Sample
          </a>
        </div>
      </div>
    `;
  }

  if (hasValue(url)) {
    return `
      <div class="embed-placeholder embed-external">
        <div class="placeholder-inner">
          <span class="placeholder-badge">External Sample</span>
          <h3>${escapeHtml(label)}</h3>
          <p class="placeholder-copy">
            This sample opens in a new tab because the source link is not available as a direct inline embed.
          </p>
          <a class="button button-primary button-small" href="${escapeHtml(url)}" target="_blank" rel="noreferrer">
            Open Sample
          </a>
        </div>
      </div>
    `;
  }

  return `
    <div class="embed-placeholder">
      <div class="placeholder-inner">
        <span class="placeholder-badge">Placeholder</span>
        <h3>${escapeHtml(label)}</h3>
        <p class="placeholder-copy">${escapeHtml(description)}</p>
      </div>
    </div>
  `;
}

